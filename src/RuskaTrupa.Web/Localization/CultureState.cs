            var source = CurrentCulture.TwoLetterISOLanguageName == "bg" ? Bulgarian : English;
            return source.TryGetValue(key, out var value) ? value : key;
        }
    }

    public void SetCulture(string cultureName)
    {
        var culture = SupportedCultures.FirstOrDefault(candidate => candidate.Name == cultureName)
            ?? SupportedCultures[0];

        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
    }
